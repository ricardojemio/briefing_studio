"""
backend/eval/run_manual_pairs.py

Runs eval/harness.py's exact matching/scoring logic against the 4 manual
"hard" pairs in eval/manual_pairs/ (real edits on real public bulas,
provided directly rather than generated by synth_generator.py), kept
separate from the 5 synthetic pairs in eval/pairs/ so easy-vs-hard results
can be compared side by side.

Does NOT modify harness.py — monkey-patches its PAIRS_DIR/RESULTS_DIR
module constants for the duration of this run only, reusing its matching
criteria (IoU threshold, greedy assignment, P/R/F1 calculation) completely
unchanged.

Run inside Docker, from backend/:
    python -m eval.run_manual_pairs
"""

from pathlib import Path

import eval.harness as harness

harness.PAIRS_DIR   = Path(__file__).parent / "manual_pairs"
harness.RESULTS_DIR = Path(__file__).parent / "manual_pairs" / "results"

if __name__ == "__main__":
    harness._print_report(harness.run())
